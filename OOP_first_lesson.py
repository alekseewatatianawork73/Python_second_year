# Инкапсуляция: уровни доступа
# Пример: аккаунт в банке.
class Account:
    def __init__(self, owner, balance):
        self.owner = owner  # публичный атрибут - имя пользователя
        self.__balance = balance  # приватный атрибут - текущий баланс на счёте

    # геттер: метод для доступа к балансу в основной программе
    def get_balance(self):
        return self.__balance


acc = Account("Иван", 1000)
print(acc.owner)  # => Иван
print(acc.__balance)   # => AttributeError
print(acc.get_balance())  # => 1000

